"""Generated documentation. Nothing summarizing the knowledge base is hand-written.

The original repository kept coverage and consistency matrices by hand, and
they drifted from the data (they reported "Yes" for mappings to heuristics that
did not exist). Here every summary is computed, and CI fails when the committed
copy differs from a fresh render.
"""

from __future__ import annotations

from collections import defaultdict

from .engine import compile_rule
from .evidence import Tier, incident_tier, inferred_step_count, rule_status
from .knowledge_base import KnowledgeBase
from .model import (
    AUTOMATABLE_SOURCES,
    Expectation,
    FixtureProvenance,
    Rule,
    ThresholdBasis,
)

HEADER = "<!-- Generated by `hyperliquid-security report`. Do not edit by hand. -->\n\n"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    def clean(cell: str) -> str:
        return cell.replace("|", "\\|").replace("\n", " ")

    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(clean(c) for c in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def _money(value: float) -> str:
    if value >= 1e6:
        return f"${value / 1e6:.2f}M"
    if value >= 1e3:
        return f"${value / 1e3:.0f}K"
    return f"${value:.0f}"


def detection_validation(rule: Rule) -> str:
    """Best evidence that the rule detects what it claims to."""
    firing = [f for f in rule.fixtures if f.expect is Expectation.fires]
    if any(f.provenance is FixtureProvenance.recorded for f in firing):
        return "recorded data"
    if any(f.provenance is FixtureProvenance.reconstructed for f in firing):
        return "reconstructed incident"
    return "synthetic only"


def render_incidents(kb: KnowledgeBase) -> str:
    rows = []
    for incident in sorted(kb.incidents.values(), key=lambda i: (i.period.start, i.id)):
        losses = (
            "; ".join(
                f"{_money(loss.amount_usd_low)}"
                + (
                    f"-{_money(loss.amount_usd_high)}"
                    if loss.amount_usd_high != loss.amount_usd_low
                    else ""
                )
                + f" {loss.basis.value} ({loss.bearer})"
                for loss in incident.losses
            )
            or "none recorded"
        )
        rows.append(
            [
                f"`{incident.id}`",
                str(incident.period.start),
                incident.control_owner,
                ", ".join(incident.mechanisms),
                incident.code_defect.value,
                incident_tier(incident).value,
                "yes" if incident.citations_checked else "no",
                f"{inferred_step_count(incident)}/{len(incident.movie)}",
                losses,
            ]
        )
    body = _table(
        [
            "Incident",
            "Start",
            "Control owner",
            "Mechanisms",
            "Code defect",
            "Derived tier",
            "Citations checked",
            "Inferred steps",
            "Losses",
        ],
        rows,
    )
    questions = []
    for incident in sorted(kb.incidents.values(), key=lambda i: i.id):
        for question in incident.open_questions:
            questions.append(f"- `{incident.id}`: {question}")
    return (
        HEADER
        + "# Incidents\n\n"
        + "Tiers are derived from cited sources (see `evidence.py`), never asserted. "
        '"Citations checked" means a reviewer read every cited source and confirmed it '
        "supports the claim citing it; unchecked tiers assume the citations are honest. "
        '"Inferred steps" counts attack-movie steps that cite no claim.\n\n'
        + body
        + "\n## Open questions\n\n"
        + ("\n".join(questions) + "\n" if questions else "None.\n")
    )


def render_rules(kb: KnowledgeBase) -> str:
    tiers = {i: incident_tier(x) for i, x in kb.incidents.items()}
    rows = []
    for rule in sorted(kb.rules.values(), key=lambda r: r.id):
        compiled = compile_rule(rule, kb.features)
        sources = sorted({kb.features[f].source.type.value for f in compiled.features})
        automatable = all(
            kb.features[f].source.type in AUTOMATABLE_SOURCES for f in compiled.features
        )
        placeholders = sum(
            1 for t in rule.thresholds.values() if t.basis is ThresholdBasis.placeholder
        )
        rows.append(
            [
                f"`{rule.id}`",
                rule.stage.value,
                rule.mode.value,
                rule.severity.value,
                rule_status([tiers[a] for a in rule.anchors if a in tiers]).value,
                detection_validation(rule),
                ", ".join(sources),
                "yes" if automatable else "no (analyst input)",
                f"{placeholders}/{len(rule.thresholds)}",
            ]
        )
    body = _table(
        [
            "Rule",
            "Stage",
            "Mode",
            "Severity",
            "Evidence status",
            "Detection validated by",
            "Data sources",
            "Automatable",
            "Placeholder thresholds",
        ],
        rows,
    )
    return (
        HEADER
        + "# Rules\n\n"
        + "*Evidence status* says whether the mechanism has been seen (from anchor tiers). "
        "*Detection validated by* says whether the rule has been shown to fire on a real case. "
        "They are different questions: a mechanism can be well documented while no rule has "
        "ever been tested against its data.\n\n" + body
    )


def render_coverage(kb: KnowledgeBase) -> str:
    tiers = {i: incident_tier(x) for i, x in kb.incidents.items()}
    observed: dict[str, list[str]] = defaultdict(list)
    for incident in kb.incidents.values():
        for primitive_id in incident.primitives:
            observed[primitive_id].append(incident.id)
    detected: dict[str, list[str]] = defaultdict(list)
    protected: dict[str, list[str]] = defaultdict(list)
    for rule in kb.rules.values():
        for primitive_id in rule.detects:
            detected[primitive_id].append(rule.id)
        for invariant_id in rule.protects:
            protected[invariant_id].append(rule.id)
    violated: dict[str, list[str]] = defaultdict(list)
    for incident in kb.incidents.values():
        for invariant_id in incident.invariants_violated:
            violated[invariant_id].append(incident.id)

    def best_tier(incident_ids: list[str]) -> str:
        order = [Tier.confirmed, Tier.credible_report, Tier.research_lead]
        found = {tiers[i] for i in incident_ids}
        return next((t.value for t in order if t in found), "-")

    primitive_rows = []
    gaps = []
    for primitive in sorted(kb.primitives.values(), key=lambda p: (p.kind.value, p.id)):
        seen = sorted(observed.get(primitive.id, []))
        rules = sorted(detected.get(primitive.id, []))
        primitive_rows.append(
            [
                f"`{primitive.id}`",
                primitive.kind.value,
                str(len(seen)),
                best_tier(seen),
                ", ".join(f"`{r}`" for r in rules) or "-",
            ]
        )
        if seen and not rules and best_tier(seen) != Tier.research_lead.value:
            gaps.append(f"- `{primitive.id}` - seen in {', '.join(seen)}; no rule detects it")
    invariant_rows = [
        [
            f"`{inv.id}`",
            str(len(violated.get(inv.id, []))),
            ", ".join(f"`{r}`" for r in sorted(protected.get(inv.id, []))) or "-",
        ]
        for inv in sorted(kb.invariants.values(), key=lambda i: i.id)
    ]
    unanchored = sorted(r.id for r in kb.rules.values() if not r.anchors)
    return (
        HEADER
        + "# Coverage\n\n## Primitives\n\n"
        + _table(["Primitive", "Kind", "Incidents", "Best tier", "Detected by"], primitive_rows)
        + "\n## Invariants\n\n"
        + _table(["Invariant", "Incidents violating", "Rules protecting"], invariant_rows)
        + "\n## Gaps\n\nPrimitives seen in credible or confirmed incidents with no rule:\n\n"
        + ("\n".join(gaps) + "\n" if gaps else "None.\n")
        + "\nRules with no anchor incident (theoretical):\n\n"
        + ("\n".join(f"- `{r}`" for r in unanchored) + "\n" if unanchored else "None.\n")
    )


def render_taxonomy(kb: KnowledgeBase) -> str:
    lines = ["flowchart LR"]
    for owner in sorted(kb.control_owners.values(), key=lambda o: o.id):
        lines.append(f'    {owner.id}["{owner.name}"]')
    for incident in sorted(kb.incidents.values(), key=lambda i: i.id):
        node = incident.id.replace("-", "_")
        mechanisms = ", ".join(incident.mechanisms)
        label = f"{incident.id}<br/>{mechanisms}<br/>{incident_tier(incident).value}"
        lines.append(f'    {node}["{label}"]')
        lines.append(f"    {incident.control_owner} --> {node}")
    return (
        HEADER + "# Incidents by control owner\n\n"
        "Each incident hangs off the party whose control failed; its mechanisms and derived "
        "tier are on the node. Two axes, not one bucket: JELLY is market manipulation "
        "(mechanism) against a core-protocol design (owner).\n\n"
        "```mermaid\n" + "\n".join(lines) + "\n```\n"
    )


def _calibrated_by(kb: KnowledgeBase, rule_id: str, threshold: str, surface: str) -> str | None:
    for result in kb.calibrations.values():
        for target in result.targets:
            if (target.rule, target.threshold, target.surface, target.applies_as) == (
                rule_id,
                threshold,
                surface,
                "profile_override",
            ):
                return result.id
    return None


def render_calibration(kb: KnowledgeBase) -> str:
    rows = []
    for rule in sorted(kb.rules.values(), key=lambda r: r.id):
        for name, threshold in sorted(rule.thresholds.items()):
            rows.append(
                [
                    f"`{rule.id}`",
                    f"`{name}`",
                    "default",
                    f"{threshold.value:g} {threshold.unit}",
                    threshold.basis.value,
                    f"`{threshold.calibration}`" if threshold.calibration else "-",
                ]
            )
            for profile in sorted(kb.profiles.values(), key=lambda p: p.surface):
                value = profile.overrides.get(rule.id, {}).get(name)
                if value is None:
                    continue
                source = _calibrated_by(kb, rule.id, name, profile.surface)
                rows.append(
                    [
                        f"`{rule.id}`",
                        f"`{name}`",
                        profile.surface,
                        f"{value:g} {threshold.unit}",
                        "calibrated" if source else "placeholder",
                        f"`{source}`" if source else "-",
                    ]
                )
    parts = [
        HEADER,
        "# Calibration\n\n",
        "Where every threshold value comes from. *calibrated* values were computed by "
        "`hyperliquid-security calibrate` from recorded data, and the validator checks the rule "
        "or profile carries exactly the computed value. *definitional* values follow from what "
        "the ratio means. *placeholder* values are judgment and should be read as such.\n\n",
        _table(["Rule", "Threshold", "Surface", "Value", "Basis", "Calibration"], rows),
    ]
    for result in sorted(kb.calibrations.values(), key=lambda r: r.id):
        parts.append(f"\n## `{result.id}` (computed {result.computed})\n\n")
        parts.append(f"**Method.** {result.method}\n\n**Data.** {result.data}\n\n")
        target_rows = [
            [f"`{t.rule}`", f"`{t.threshold}`", t.surface, t.applies_as, f"{t.value:g}"]
            for t in result.targets
        ]
        parts.append(_table(["Rule", "Threshold", "Surface", "Applied as", "Value"], target_rows))
        if result.checks:
            parts.append("\n**Checks against incidents.**\n\n")
            parts.append("".join(f"- {c.description}: {c.outcome}\n" for c in result.checks))
        if result.limitations:
            parts.append("\n**Limitations.**\n\n")
            parts.append("".join(f"- {item}\n" for item in result.limitations))
        for surface, detail in sorted(result.results.items()):
            if not isinstance(detail, dict):
                continue
            parts.append(f"\n**{surface}.** ")
            summary = {
                k: v
                for k, v in detail.items()
                if not isinstance(v, (list, dict)) and k != "surface"
            }
            parts.append(", ".join(f"{k}: {v}" for k, v in summary.items()) + "\n\n")
            if isinstance(detail.get("quantiles"), dict):
                quantiles = detail["quantiles"]
                parts.append(_table(list(quantiles), [[str(v) for v in quantiles.values()]]))
            listed = detail.get("above_threshold") or detail.get("episodes_by_market") or []
            if listed:
                label = (
                    "At or above threshold" if "above_threshold" in detail else "Episodes by market"
                )
                shown = ", ".join(
                    f"{item['market']} ({item.get('median', item.get('episodes'))})"
                    for item in listed[:20]
                )
                more = f", and {len(listed) - 20} more" if len(listed) > 20 else ""
                parts.append(f"\n{label}: {shown}{more}.\n")
    return "".join(parts)


def render_all(kb: KnowledgeBase) -> dict[str, str]:
    return {
        "incidents.md": render_incidents(kb),
        "rules.md": render_rules(kb),
        "coverage.md": render_coverage(kb),
        "taxonomy.md": render_taxonomy(kb),
        "calibration.md": render_calibration(kb),
    }
